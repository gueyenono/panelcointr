test_that("westerlund_control() keeps the supplied settings and validates them", {
  ctl <- westerlund_control(t_norm = "df", boot_burn = 20)
  expect_s3_class(ctl, "westerlund_control")
  expect_identical(ctl$t_norm, "df")
  expect_identical(ctl$boot_burn, 20L)
  expect_null(ctl$panel_lags)
  expect_error(westerlund_control(t_norm = "x"), "`t_norm` must be one of")
  expect_error(westerlund_control(demean_u = NA), "TRUE or FALSE")
  expect_error(westerlund_control(boot_chunk = 0), "at least 1")
  expect_output(print(ctl), "t_norm: df")
})

test_that("settings resolve as control, then compat preset, then default", {
  s <- resolve_westerlund_settings("none", westerlund_control(), "trend", "aic")
  expect_identical(s$t_norm, "effective")
  expect_true(s$demean_u)
  expect_null(s$lrwindow)
  s <- resolve_westerlund_settings("xtwest", westerlund_control(t_norm = "T"), "trend", "bic")
  expect_identical(s$t_norm, "T")
  expect_identical(s$panel_lags, "mean")
  expect_identical(s$criterion, "bic")
  expect_identical(s$lrwindow, 2L)
  s <- resolve_westerlund_settings("xtwest_westerlund", westerlund_control(), "constant", "aic")
  expect_identical(s$criterion, "westerlund")
  expect_identical(s$moments, "legacy")
  expect_identical(s$boot_pvalue, "plus_one")
})

test_that("the resolved settings are stored in the result", {
  fit <- hce_fit(lags = 1, compat = "xtwest", control = westerlund_control(demean_u = TRUE))
  expect_true(fit$settings$demean_u)
  expect_identical(fit$settings$compat, "xtwest")
  expect_identical(fit$settings$lrwindow, 2L)
  expect_identical(fit$settings$lags, c(1L, 1L))
  expect_equal(fit$settings$moment_values, westerlund_moments("trend", 1))
})
